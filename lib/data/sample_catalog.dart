      'Dấu vết cuối cùng dẫn đến nơi bắt đầu. Ở đó, quá khứ chờ sẵn với một bí mật chưa từng được kể.',
      'Thử thách buộc mọi người phải tin tưởng nhau. Một sự thật mới làm thay đổi cách họ nhìn về đối thủ.',
