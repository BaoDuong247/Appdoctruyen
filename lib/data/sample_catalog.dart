  static Novel _sample({
    required String id,
    required String title,
    required String author,
    required String cover,
    required String category,
    required double rating,
    required int views,
    required String description,
    required List<String> titles,
    required List<String> moments,
  }) => Novel(
    id: id,
    title: title,
    author: author,
    coverUrl: 'asset:assets/covers/$cover',
    category: category,
    description: description,
    rating: rating,
    viewCount: views,
    status: 'Đang ra',
    chapters: List.generate(
      10,
      (index) => ChapterContent(
        chapterNumber: index + 1,
        title: titles[index],
        content: '${moments[index]}\n\n${_continuation(index, title, author)}',
      ),
    ),
  );

